app.post('/api/chat', async (req, res) => {
  try {
    const { message } = req.body;
    
    // バリデーション
    if (!message || typeof message !== 'string' || message.trim().length === 0) {
      return res.status(400).json({
        success: false,
        error: 'メッセージが必要です'
      });
    }
    
    if (message.length > 1000) {
      return res.status(400).json({
        success: false,
        error: 'メッセージが長すぎます'
      });
    }
    
    // 簡易使用量チェック（高速化）
    const usageCheck = await checkDailyUsage();
    
    // OpenAI API呼び出し（高速化のためGPT-4o-miniを使用）
    const completion = await openai.chat.completions.create({
      model: 'gpt-4o-mini',
      messages: [
        {
          role: 'system',
          content: clinicSystemPrompt
        },
        {
          role: 'user',
          content: message.trim()
        }
      ],
      temperature: 0.7,
      max_tokens: 500
    });
    
    const response = completion.choices[0].message.content;
    
    // 使用量更新（簡易ログ）
    await updateDailyUsage();
    
    // レスポンス（シンプル化）
    res.json({
      success: true,
      response: response
    });
    
  } catch (error) {
    console.error('Chat API error:', error);
    
    if (error.code === 'insufficient_quota') {
      return res.status(503).json({
        success: false,
        error: 'サービスが一時的に利用できません。お電話でお問い合わせください。',
        code: 'SERVICE_UNAVAILABLE'
      });
    }
    
    if (error.code === 'rate_limit_exceeded') {
      return res.status(429).json({
        success: false,
        error: 'サーバーが混雑しています。しばらく待ってからお試しください。',
        code: 'SERVER_BUSY'
      });
    }
    
    res.status(500).json({
      success: false,
      error: 'サーバーエラーが発生しました。お電話でお問い合わせください。',
      code: 'INTERNAL_ERROR'
    });
  }
});

